    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
         JTable targetTable = null;
        String tableType = "";

        // 🧩 Determine which table has a selected row
        if (tblPending.getSelectedRow() != -1) {
            targetTable = tblPending;
            tableType = "pending";
        } else if (tblApproved.getSelectedRow() != -1) {
            targetTable = tblApproved;
            tableType = "approved";
        } else if (tblRejected.getSelectedRow() != -1) {
            targetTable = tblRejected;
            tableType = "rejected";
        }

        if (targetTable == null) {
            JOptionPane.showMessageDialog(this, "Select a request to delete!");
            return;
        }

        int row = targetTable.getSelectedRow();
        int requestId = (int) targetTable.getValueAt(row, 0);

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this request?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try (Connection conn = DBConnection.connect()) {
            // 🗑️ Delete request from database
            String sql = "DELETE FROM anime_requests WHERE user_id=? AND title=?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, (int) targetTable.getValueAt(row, 0)); // user_id
            ps.setString(2, targetTable.getValueAt(row, 2).toString()); // title

            int deleted = ps.executeUpdate();

            if (deleted > 0) {
                JOptionPane.showMessageDialog(this, "Request deleted successfully!");
                // 🔁 Refresh all tables to keep in sync
                loadRequests("pending", tblPending);
                loadRequests("approved", tblApproved);
                loadRequests("rejected", tblRejected);
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete request. It may not exist.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

