    private void btnApprovedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApprovedActionPerformed
        // TODO add your handling code here:
        
         int row = tblPending.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select a request first!");
            return;
        }

        int userId = Integer.parseInt(tblPending.getValueAt(row, 0).toString());
        String title = tblPending.getValueAt(row, 2).toString();

        try (Connection conn = DBConnection.connect()) {
            String sql = "UPDATE anime_requests SET status='approved' WHERE user_id=? AND title=?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, userId);
            ps.setString(2, title);

            int updated = ps.executeUpdate();
            if (updated > 0) {
                String notifSql = "INSERT INTO notifications (user_id, message) VALUES (?, ?)";
                PreparedStatement notifPs = conn.prepareStatement(notifSql);
                notifPs.setInt(1, userId);
                notifPs.setString(2, "✅ Your anime request '" + title + "' has been approved!");
                notifPs.executeUpdate();

                JOptionPane.showMessageDialog(this, "Request approved & user notified!");
            } else {
                JOptionPane.showMessageDialog(this, "Failed to approve request.");
            }

            loadRequests("pending", tblPending);
            loadRequests("approved", tblApproved);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
        
    }//GEN-LAST:event_btnApprovedActionPerformed

    private void btnRejectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRejectActionPerformed
        int row = tblPending.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select a request first!");
            return;
        }

        // ✅ Corrected column indexes
        int userId = Integer.parseInt(tblPending.getValueAt(row, 0).toString()); // user_id
        String title = tblPending.getValueAt(row, 2).toString(); // title

        try (Connection conn = DBConnection.connect()) {
            // ❌ Update status to "rejected"
            String sql = "UPDATE anime_requests SET status='rejected' WHERE user_id=? AND title=?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, userId);
            ps.setString(2, title);

            int updated = ps.executeUpdate();

            if (updated > 0) {
                // 🔔 Add notification for user
                String notifSql = "INSERT INTO notifications (user_id, message) VALUES (?, ?)";
                PreparedStatement notifPs = conn.prepareStatement(notifSql);
                notifPs.setInt(1, userId);
                notifPs.setString(2, "❌ Your anime request '" + title + "' has been rejected.");
                notifPs.executeUpdate();

                JOptionPane.showMessageDialog(this, "Request rejected & user notified!");
            } else {
                JOptionPane.showMessageDialog(this, "Failed to reject request.");
                return;
            }

            // 🔄 Refresh tables
            loadRequests("pending", tblPending);
            loadRequests("rejected", tblRejected);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }

    }//GEN-LAST:event_btnRejectActionPerformed

