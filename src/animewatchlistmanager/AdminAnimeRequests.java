    private void loadRequests(String status, JTable table) {
        
    try (Connection conn = DBConnection.connect()) {
        String sql = "SELECT ar.user_id, u.username, ar.title, ar.comment, ar.status, ar.created_at " +
             "FROM anime_requests ar " +
             "JOIN users u ON ar.user_id = u.user_id " +
             "WHERE ar.status = ? " +
             "ORDER BY ar.created_at DESC";

        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setString(1, status);
        ResultSet rs = ps.executeQuery();

        DefaultTableModel model = (DefaultTableModel) table.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("user_id"),
                rs.getString("username"),
                rs.getString("title"),
                rs.getString("comment"),
                rs.getString("status"),
                rs.getString("created_at")
            });
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}
    private void updateRequestStatus(int id, String status) {
    try (Connection conn = DBConnection.connect()) {
        String sql = "UPDATE anime_requests SET status=? WHERE id=?";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setString(1, status);
        ps.setInt(2, id);
        ps.executeUpdate();

        JOptionPane.showMessageDialog(this, "Request " + status + "!");
        loadRequests("pending", tblPending);
        loadRequests("approved", tblApproved);
        loadRequests("rejected", tblRejected);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}
    
       


