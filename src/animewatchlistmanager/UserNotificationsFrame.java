    private void btnClearNotifActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnClearNotifActionPerformed
        // TODO add your handling code here:
         int confirm = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to clear all notifications?",
                "Confirm Clear", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try (Connection conn = DBConnection.connect()) {
                String sql = "DELETE FROM notifications WHERE user_id = ?";
                PreparedStatement ps = conn.prepareStatement(sql);
                ps.setInt(1, currentUserId);
                int deleted = ps.executeUpdate();

                if (deleted > 0) {
                    JOptionPane.showMessageDialog(this, "✅ All notifications cleared!");
                } else {
                    JOptionPane.showMessageDialog(this, "No notifications to clear.");
                }

                loadNotifications(); // Refresh the table

            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error clearing notifications: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnClearNotifActionPerformed

