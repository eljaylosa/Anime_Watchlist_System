    private void loadNotifications() {
    try (Connection conn = DBConnection.connect()) {
        String sql = "SELECT message, created_at FROM notifications WHERE user_id = ? ORDER BY created_at DESC";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setInt(1, currentUserId);
        ResultSet rs = ps.executeQuery();

        // 🧩 Update table model with two columns: Message + Added At
        DefaultTableModel model = new DefaultTableModel(
            new Object[]{"Message", "Added at"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        int count = 0; // limit toast spam

        while (rs.next()) {
            String message = rs.getString("message");
            Timestamp timestamp = rs.getTimestamp("created_at");

            // Format date/time for readability (e.g., "Nov 5, 2025 10:43 PM")
            String formattedDate = new java.text.SimpleDateFormat("MMM dd, yyyy hh:mm a").format(timestamp);

            model.addRow(new Object[]{ message, formattedDate });

            // 🔔 Show toast for the first 3 notifications only
            if (count < 3) {
                NotificationUtil.showToast(message);
            }
            count++;
        }

        tblNotifications.setModel(model);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error loading notifications: " + e.getMessage());
    }
}





